#!/usr/bin/env python3
"""Generates tests/audio/fixtures.h: small Ogg Vorbis, Ogg Opus and FLAC files made with libsndfile (python package `soundfile`).

The signals are sums of sines with known frequencies, so the C++ tests can check the decoders without a bit-exact reference for the lossy
formats (frequency / level / channel order); the FLAC file is lossless and is compared sample by sample with the PCM that is embedded next to it.
Not run by the build. Needs: pip install soundfile numpy
Run:  python3 tests/audio/gen_fixtures.py > tests/audio/fixtures.h
"""
import io
import sys
import numpy as np
import soundfile as sf


def tone(freq, rate, frames, amp=0.5):
    t = np.arange(frames) / rate
    return amp * np.sin(2 * np.pi * freq * t)


def encode(data, rate, fmt, subtype, **tags):
    bio = io.BytesIO()
    with sf.SoundFile(bio, 'w', samplerate=rate, channels=data.shape[1], format=fmt, subtype=subtype) as f:
        for k, v in tags.items():
            setattr(f, k, v)
        f.write(data)
    return bio.getvalue()


def c_array(name, data, ctype='uint8_t'):
    out = []
    for i in range(0, len(data), 16):
        out.append('    ' + ', '.join('0x%02X' % b for b in data[i:i + 16]) + ',')
    return 'static const %s %s[%d] = {\n%s\n};\n' % (ctype, name, len(data), '\n'.join(out))


def main():
    o = ['// GENERATED by tests/audio/gen_fixtures.py (libsndfile 1.2.x) - do not edit.\n#pragma once\n#include <cstdint>\n']

    # Vorbis stereo: L = 440 Hz, R = 660 Hz, 22050 Hz, 0.5 s
    rate, n = 22050, 11025
    st = np.stack([tone(440, rate, n), tone(660, rate, n)], axis=1)
    o.append(c_array('vorbis_stereo', encode(st, rate, 'OGG', 'VORBIS', title='NUE Vorbis')))
    o.append('static const uint32_t vorbis_stereo_rate = %d, vorbis_stereo_frames = %d;\n' % (rate, n))

    # Vorbis 5.1 in Vorbis channel order: FL FC FR BL BR LFE with distinct tones per file channel
    rate, n = 16000, 4000
    freqs = [300 + 200 * k for k in range(6)]
    six = np.stack([tone(f, rate, n, 0.3) for f in freqs], axis=1)
    o.append(c_array('vorbis_6ch', encode(six, rate, 'OGG', 'VORBIS')))
    o.append('static const uint32_t vorbis_6ch_rate = %d, vorbis_6ch_frames = %d;\n' % (rate, n))
    o.append('static const float vorbis_6ch_freqs[6] = {%s};\n' % ', '.join('%d.0f' % f for f in freqs))

    # Opus stereo 48 kHz, 1 s
    rate, n = 48000, 48000
    op = np.stack([tone(440, rate, n), tone(660, rate, n)], axis=1)
    o.append(c_array('opus_stereo', encode(op, rate, 'OGG', 'OPUS', title='NUE Opus')))
    o.append('static const uint32_t opus_stereo_rate = %d, opus_stereo_frames = %d;\n' % (rate, n))

    # FLAC 16 bit stereo, 22050 Hz, 0.1 s: lossless, the PCM follows
    rate, n = 22050, 2205
    pcm = np.stack([np.round(16000 * np.sin(2 * np.pi * 440 * np.arange(n) / rate)),
                    np.round(9000 * np.sin(2 * np.pi * 1234 * np.arange(n) / rate) + 3000 * np.sin(2 * np.pi * 77 * np.arange(n) / rate))], axis=1).astype('<i2')
    o.append(c_array('flac_stereo', encode(pcm, rate, 'FLAC', 'PCM_16', title='NUE FLAC')))
    o.append(c_array('flac_stereo_pcm', pcm.tobytes()))
    o.append('static const uint32_t flac_stereo_rate = %d, flac_stereo_frames = %d;\n' % (rate, n))
    sys.stdout.write('\n'.join(o))


main()
