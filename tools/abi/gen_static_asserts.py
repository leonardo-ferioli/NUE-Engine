#!/usr/bin/env python3
"""Turns a committed ABI reference (tests/abi/reference/<layout>.txt) into a C++ file of static_asserts, so that ANY compiler/target can check the public
headers against the reference without running anything (cross builds: Linux from Windows, Android, iOS).

    gen_static_asserts.py tests/abi/reference/ptr64.txt out.cpp
    zig c++ -target x86_64-linux-gnu -std=c++17 -Iinclude -fsyntax-only out.cpp

Compilation fails (static_assert) where the target's layout differs from the reference. Functions are not checked (a declaration check needs the signature).
"""
import sys


def main():
    ref, out = sys.argv[1], sys.argv[2]
    headers = set()
    lines = []
    for raw in open(ref, encoding='utf-8'):
        raw = raw.rstrip('\n')
        if not raw or raw.startswith('#') or raw.startswith('version '):
            continue
        parts = raw.split(' ')
        group, kind, name = parts[0], parts[1], parts[2]
        value = ' '.join(parts[3:])
        if kind == 'struct':
            size = value.split('size=')[1].split(' ')[0]
            align = value.split('align=')[1]
            lines.append('static_assert(sizeof(%s) == %s, "sizeof %s");' % (name, size, name))
            lines.append('static_assert(alignof(%s) == %s, "alignof %s");' % (name, align, name))
        elif kind == 'field':
            st, member = name.split('.', 1)
            off = value.split('off=')[1].split(' ')[0]
            size = value.split('size=')[1]
            lines.append('static_assert(offsetof(%s, %s) == %s, "offsetof %s");' % (st, member, off, name))
            lines.append('static_assert(sizeof(((%s*)0)->%s) == %s, "sizeof member %s");' % (st, member, size, name))
        elif kind == 'enum':
            lines.append('static_assert((long long)(%s) == %sLL, "enum %s");' % (name, value, name))
        elif kind == 'define':
            lines.append('static_assert((unsigned long long)(%s) == %sULL, "define %s");' % (name, value, name))
    text = '// GENERATED by tools/abi/gen_static_asserts.py from %s - do not edit\n#include <cstddef>\n' % ref.replace('\\', '/').split('/')[-1]
    import os
    inc = sorted(f for f in os.listdir(os.path.join(os.path.dirname(os.path.abspath(ref)), '..', '..', '..', 'include', 'nue')) if f.endswith('.h'))
    for h in inc:
        text += '#include "nue/%s"\n' % h
    text += '\n'.join(lines) + '\n'
    open(out, 'w', encoding='utf-8', newline='\n').write(text)
    sys.stderr.write('%d static_asserts written to %s\n' % (len(lines), out))


if __name__ == '__main__':
    main()
