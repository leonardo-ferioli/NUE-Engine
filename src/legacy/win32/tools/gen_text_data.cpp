// Generates legacy_win32/src/text_data.inc from the real Windows national-language support: the facts the portable text module cannot compute
// (character classes, case mapping, collation weights of the Latin / Greek / Cyrillic repertoire, code page tables, en-US locale strings).
// Only the data is taken (it is what Windows answers to documented API calls, not Windows code). Windows only; run once when the tables change:
//     clang++ -O1 -o gen_text_data.exe gen_text_data.cpp && gen_text_data.exe > ../src/text_data.inc
#define WIN32_LEAN_AND_MEAN
#define NOMINMAX
#include <windows.h>
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

static const unsigned kLast = 0x4FF;   // U+0000 .. U+04FF: Latin, Greek, Cyrillic

int main() {
    std::printf("// Generated by tools/gen_text_data.cpp from the Windows NLS answers (see that file). Do not edit by hand.\n");
    // Character classes
    for (int type : {1, 2, 3}) {
        std::printf("static const uint16_t kCType%d[0x%X] = {", type, kLast + 1);
        for (unsigned c = 0; c <= kLast; ++c) {
            WCHAR ch = WCHAR(c);
            WORD r = 0;
            GetStringTypeW(type == 1 ? CT_CTYPE1 : type == 2 ? CT_CTYPE2 : CT_CTYPE3, &ch, 1, &r);
            std::printf("%s0x%X,", c % 16 == 0 ? "\n    " : "", r);
        }
        std::printf("\n};\n");
    }
    // Case mapping: only the characters that change
    for (int upper = 0; upper < 2; ++upper) {
        std::printf("static const uint16_t k%sMap[][2] = {", upper ? "Upper" : "Lower");
        int n = 0;
        for (unsigned c = 0; c <= kLast; ++c) {
            WCHAR ch = WCHAR(c), out = 0;
            LCMapStringW(0x0409, upper ? LCMAP_UPPERCASE : LCMAP_LOWERCASE, &ch, 1, &out, 1);
            if (out != ch) std::printf("%s{0x%X,0x%X},", n++ % 8 == 0 ? "\n    " : "", c, unsigned(out));
        }
        std::printf("\n};\n");
    }
    // Code pages: bytes 0x80..0xFF
    for (unsigned cp : {437u, 850u, 1252u, 28591u}) {
        std::printf("static const uint16_t kCp%u[128] = {", cp);
        for (unsigned b = 0x80; b <= 0xFF; ++b) {
            char byte = char(b);
            WCHAR w = 0xFFFD;
            MultiByteToWideChar(cp, 0, &byte, 1, &w, 1);
            std::printf("%s0x%X,", (b - 0x80) % 16 == 0 ? "\n    " : "", unsigned(w));
        }
        std::printf("\n};\n");
    }
    // Collation: the sort key of every single character (as hex bytes), for the characters that have one.
    std::printf("struct SortKeyEntry { uint16_t c; uint8_t length; const char* bytes; };\n");
    std::printf("static const SortKeyEntry kSortKeys[] = {\n");
    for (unsigned c = 0; c <= kLast; ++c) {
        WCHAR ch = WCHAR(c);
        BYTE key[64];
        const int n = LCMapStringW(0x0409, LCMAP_SORTKEY, &ch, 1, reinterpret_cast<LPWSTR>(key), sizeof key);
        if (n <= 0) continue;
        std::printf("    {0x%X,%d,\"", c, n);
        for (int i = 0; i < n; ++i) std::printf("\\x%02X", key[i]);
        std::printf("\"},\n");
    }
    std::printf("};\n");
    // Sort keys under SORT_STRINGSORT, only for the characters whose key differs from the word sort key (hyphen, apostrophe...).
    std::printf("static const SortKeyEntry kSortKeysString[] = {\n");
    for (unsigned c = 0; c <= kLast; ++c) {
        WCHAR ch = WCHAR(c);
        BYTE a[64], b[64];
        const int na = LCMapStringW(0x0409, LCMAP_SORTKEY, &ch, 1, reinterpret_cast<LPWSTR>(a), sizeof a);
        const int nb = LCMapStringW(0x0409, LCMAP_SORTKEY | SORT_STRINGSORT, &ch, 1, reinterpret_cast<LPWSTR>(b), sizeof b);
        if (nb <= 0 || (na == nb && std::memcmp(a, b, size_t(na)) == 0)) continue;
        std::printf("    {0x%X,%d,\"", c, nb);
        for (int i = 0; i < nb; ++i) std::printf("\\x%02X", b[i]);
        std::printf("\"},\n");
    }
    std::printf("};\n");
    // Best fit: characters a single-byte code page does not have but Windows maps (without the default character) to another byte.
    std::printf("struct BestFit { uint16_t c; uint8_t byte; };\n");
    for (unsigned cp : {437u, 850u, 1252u, 28591u}) {
        std::printf("static const BestFit kBestFit%u[] = {", cp);
        int n = 0;
        for (unsigned c = 0x80; c <= 0xFFFF; ++c) {   // the whole BMP: best fit reaches far (infinity sign to '8', fullwidth letters...)
            if (c >= 0xD800 && c <= 0xDFFF) continue;
            WCHAR ch = WCHAR(c);
            char out[4] = {};
            BOOL used = FALSE;
            if (WideCharToMultiByte(cp, 0, &ch, 1, out, 4, nullptr, &used) != 1 || used) continue;
            WCHAR back = 0;
            MultiByteToWideChar(cp, 0, out, 1, &back, 1);
            if (back == ch) continue;   // a direct mapping: in the code page table
            std::printf("%s{0x%X,0x%X},", n++ % 8 == 0 ? "\n    " : "", c, unsigned(static_cast<unsigned char>(out[0])));
        }
        std::printf("\n    {0,0}};\n");
    }
    // The same for the string "ab" and the empty string, to document the layout the assembler must reproduce.
    // Locale info of en-US (0x0409) without user overrides: every LCTYPE 0..0x1100 that answers.
    std::printf("struct LocaleEntry { uint32_t type; uint32_t length; const char16_t* text; };\n");
    std::printf("static const LocaleEntry kLocaleEnUs[] = {\n");
    for (unsigned type = 0; type <= 0x1100; ++type) {
        if (type > 0x120 && type < 0x1000) continue;
        if (type == 0x2 || type == 0x6 || type == 0x6F) continue;   // display names in the UI language of this machine: written by hand in text.cpp (English)
        WCHAR buffer[512];
        const int n = GetLocaleInfoW(0x0409, type | LOCALE_NOUSEROVERRIDE, buffer, 512);
        if (n <= 0) continue;
        // `length` is the count Windows returns; the literal holds the characters before a terminating NUL (the literal's own NUL is that terminator).
        // LOCALE_FONTSIGNATURE is 16 words with no terminator at all.
        std::printf("    {0x%X,%d,u\"", type, n);
        for (int i = 0; i < (buffer[n - 1] == 0 ? n - 1 : n); ++i) {
            if (buffer[i] < 0x20 || buffer[i] > 0x7E || buffer[i] == '"' || buffer[i] == '\\' || buffer[i] == '?') std::printf("\\x%04X\" u\"", unsigned(buffer[i]));
            else std::printf("%c", char(buffer[i]));
        }
        std::printf("\"},\n");
    }
    std::printf("};\n");
    return 0;
}
